<?php

namespace App\Support\Reports;

use Illuminate\Support\Collection;

/**
 * ReportResult
 *
 * One shape returned by every report service, so a single Blade shell can
 * render any report and a single export service can serialise any report
 * without knowing which one it is.
 *
 * - summary: KPI cards across the top
 * - rows: the detail table, already aggregated in SQL
 * - columns: table column definitions (key, label, alignment, formatting)
 * - totals: optional footer row
 * - chart: optional bar chart series
 * - meta: self-describing context — report name, branch, range, who ran it
 */
final class ReportResult
{
    /**
     * @param  list<array{key: string, label: string, value: string, hint?: ?string, trend?: ?array{direction: string, label: string}, icon?: ?string}>  $summary
     * @param  Collection<int, array<string, mixed>>  $rows
     * @param  list<array{key: string, label: string, align?: string, format?: string}>  $columns
     * @param  array<string, mixed>  $totals
     * @param  ?array{title: string, unit: string, points: list<array{label: string, value: float, display: string, percent: float}>}  $chart
     * @param  array<string, mixed>  $meta
     */
    public function __construct(
        public readonly string $key,
        public readonly string $title,
        public readonly array $summary = [],
        public readonly Collection $rows = new Collection,
        public readonly array $columns = [],
        public readonly array $totals = [],
        public readonly ?array $chart = null,
        public readonly array $meta = [],
    ) {}

    /**
     * Whether the detail table has anything to show.
     *
     * Drives the empty state. A zero-row report on a fresh branch is a normal
     * outcome, not an error, and must never render as a broken table.
     */
    public function isEmpty(): bool
    {
        return $this->rows->isEmpty();
    }

    /**
     * Copy with the meta bag merged — used to stamp the "generated by" and
     * branch context on a result the service built without knowing the actor.
     *
     * @param  array<string, mixed>  $meta
     */
    public function withMeta(array $meta): self
    {
        return new self(
            $this->key,
            $this->title,
            $this->summary,
            $this->rows,
            $this->columns,
            $this->totals,
            $this->chart,
            array_merge($this->meta, $meta),
        );
    }

    /**
     * Read one meta value.
     */
    public function meta(string $key, mixed $default = null): mixed
    {
        return $this->meta[$key] ?? $default;
    }

    /**
     * Build a chart series with server-computed bar percentages.
     *
     * Percentages are computed here, not in Blade, so the view never contains
     * arithmetic and the bar width can be handed to CSS as a custom property.
     *
     * @param  list<array{label: string, value: float|int, display: string}>  $points
     * @param  string  $orientation 'horizontal' for a category breakdown, 'vertical' for a time series
     * @return array{title: string, unit: string, orientation: string, points: list<array{label: string, value: float, display: string, percent: float}>}
     */
    public static function chart(string $title, string $unit, array $points, string $orientation = 'horizontal'): array
    {
        $max = 0.0;

        foreach ($points as $point) {
            $max = max($max, (float) $point['value']);
        }

        $scaled = [];

        foreach ($points as $point) {
            $value = (float) $point['value'];

            $scaled[] = [
                'label' => $point['label'],
                'value' => $value,
                'display' => $point['display'],
                // A zero max would divide by zero; a flat all-zero series shows
                // empty tracks, which is the honest representation.
                'percent' => $max > 0 ? round($value / $max * 100, 2) : 0.0,
            ];
        }

        return [
            'title' => $title,
            'unit' => $unit,
            'orientation' => $orientation,
            'points' => $scaled,
        ];
    }
}
